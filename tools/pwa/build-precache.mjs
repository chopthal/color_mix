/**
 * precache 목록 생성 스크립트 (Node, 외부 의존 0)
 *
 * 레포를 훑어 배포 대상 정적 파일을 모아 루트의 `sw-precache.js`를 생성한다.
 *  - self.PRECACHE: 루트 기준 상대 URL 목록 (서브패스 배포에 안전)
 *  - self.PRECACHE_VERSION: 전체 내용의 sha256 앞 16자리
 *
 * 사용: `node tools/pwa/build-precache.mjs`
 * 에셋이 바뀌면 반드시 재실행한다.
 */
import { readdir, readFile, writeFile, stat } from 'node:fs/promises';
import { join, relative, extname, sep } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const TOOLS_DIR = fileURLToPath(new URL('.', import.meta.url));
const ROOT = join(TOOLS_DIR, '..', '..');
const OUT_FILE = join(ROOT, 'sw-precache.js');

// 배포 대상 확장자 (화이트리스트)
const INCLUDE_EXT = new Set([
  '.html', '.css', '.js', '.json',
  '.webp', '.png', '.svg', '.jpg', '.jpeg', '.gif', '.ico', '.avif',
  '.woff2', '.woff', '.ttf', '.otf',
  '.mp3', '.wav', '.ogg', '.m4a',
  '.webmanifest',
]);

// 디렉터리 제외
const EXCLUDE_DIRS = new Set([
  '.git', 'docs', 'tools', 'node_modules', '.vercel', '.cursor', '.playwright-mcp',
]);

// 개별 파일 제외 (확장자 무관)
const EXCLUDE_FILES = new Set([
  'sw.js',          // SW 본체 — 브라우저가 직접 갱신
  'sw-precache.js', // 이 스크립트가 생성하는 목록
  'demo.html',      // games/_shared 데모 (배포 안 함)
]);

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (EXCLUDE_DIRS.has(entry.name)) continue;
      files.push(...(await walk(full)));
    } else if (entry.isFile()) {
      files.push(full);
    }
  }
  return files;
}

function toUrlPath(rel) {
  return rel.split(sep).join('/');
}

async function main() {
  const all = await walk(ROOT);
  const included = [];

  for (const file of all) {
    const rel = relative(ROOT, file);
    const base = rel.split(sep).pop();
    const ext = extname(file).toLowerCase();
    if (EXCLUDE_FILES.has(base)) continue;
    if (!INCLUDE_EXT.has(ext)) continue;
    included.push(file);
  }

  // URL 경로 기준 정렬 (결정적 출력)
  const items = included
    .map((f) => toUrlPath(relative(ROOT, f)))
    .sort();

  // 내용 해시 (경로 + 파일 내용)
  const hash = createHash('sha256');
  for (const rel of items) {
    hash.update(rel);
    hash.update('\0');
    hash.update(await readFile(join(ROOT, rel)));
    hash.update('\n');
  }
  const version = hash.digest('hex').slice(0, 16);

  const body =
    '// GENERATED by tools/pwa/build-precache.mjs — do not edit.\n' +
    '// 재생성: node tools/pwa/build-precache.mjs\n' +
    `self.PRECACHE_VERSION = '${version}';\n` +
    `self.PRECACHE = ${JSON.stringify(items, null, 2)};\n`;

  await writeFile(OUT_FILE, body, 'utf8');

  // 총 용량 계산 (보고용)
  let total = 0;
  for (const rel of items) {
    const st = await stat(join(ROOT, rel));
    total += st.size;
  }

  console.log(`sw-precache.js: ${items.length} files, ${(total / 1024 / 1024).toFixed(2)} MB, version ${version}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
